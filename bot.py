def _collect_source_urls(response):

    citations = []
    seen = set()

    try:

        for item in (
            getattr(
                response,
                "output",
                []
            )
            or []
        ):

            for content in (
                getattr(
                    item,
                    "content",
                    []
                )
                or []
            ):

                for annotation in (
                    getattr(
                        content,
                        "annotations",
                        []
                    )
                    or []
                ):

                    url = getattr(
                        annotation,
                        "url",
                        None
                    )

                    if not url:
                        continue

                    if url in seen:
                        continue

                    seen.add(url)

                    citations.append(
                        {
                            "url": url,
                            "title": getattr(
                                annotation,
                                "title",
                                None
                            ),
                        }
                    )

    except Exception as e:

        print(
            f"SOURCE EXTRACTION WARNING: {e}"
        )

    return citations[:10]


