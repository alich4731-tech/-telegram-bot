# =========================================================
# نمایش لینک‌های ۹ قسمت نیمه پیشرفته
# =========================================================

async def excel_intermediate_download(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    context.user_data[
        "menu_level"
    ] = "excel_intermediate_download"

    inline_keyboard = []

    for index, lesson in enumerate(
        INTERMEDIATE_LESSONS,
        start=1
    ):

        # شماره قسمت در خط اول و عنوان کامل در خط دوم
        # قرار می‌گیرد تا عنوان در موبایل فضای بیشتری داشته باشد.
        button_text = (
            f"{index}\n"
            f"{lesson['topic']}"
        )

        inline_keyboard.append(
            [
                InlineKeyboardButton(
                    text=button_text,
                    url=lesson["url"],
                )
            ]
        )

    reply_markup = InlineKeyboardMarkup(
        inline_keyboard
    )

    await update.message.reply_text(
        "📘 ویدئوهای آموزشی نیمه پیشرفته اکسل\n\n"
        "برای مشاهده هر قسمت، موضوع مورد نظر را انتخاب کنید:",
        reply_markup=reply_markup,
    )


# =========================================================
# بازگشت
# =========================================================

async def back(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    level = context.user_data.get(
        "menu_level"
    )

    if level == "ai":

        context.user_data[
            "ai_mode"
        ] = False

        await start(
            update,
            context
        )

    elif level in [
        "in_person_courses",
        "online_courses",
    ]:

        await courses(
            update,
            context
        )

    elif level in [
        "tax_system",
        "power_query",
    ]:

        await in_person_courses(
            update,
            context
        )

    elif level == "power_query_link":

        await power_query(
            update,
            context
        )

    elif level in [
        "instagram",
        "telegram",
        "rubika",
    ]:

        await contact(
            update,
            context
        )

    elif level == "excel_beginner":

        await educational_videos(
            update,
            context
        )

    elif level == "excel_beginner_download":

        await excel_beginner(
            update,
            context
        )

    elif level == "excel_intermediate":

        await educational_videos(
            update,
            context
        )

    elif level == "excel_intermediate_download":

        # بازگشت اول:
        # از فهرست ۹ قسمت به صفحه نیمه پیشرفته
        await excel_intermediate(
            update,
            context
        )

    else:

        await start(
            update,
            context
        )


