async def ask_ai(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    if not context.user_data.get(
        "ai_mode",
        False
    ):
        return

    # =====================================================
    # کنترل عضویت قبل از هر سؤال متنی
    # =====================================================

    is_member = await ensure_ai_membership(
        update,
        context
    )

    if not is_member:
        return

    user_question = (
        update.message.text
        or ""
    ).strip()[:3000]

    if not user_question:
        return

    if (
        not OPENAI_API_KEY
        or client is None
    ):

        await update.message.reply_text(
            "⚠️ اتصال دستیار هوشمند تنظیم نشده است.\n"
            "OPENAI_API_KEY را در Environment Variables بررسی کنید."
        )

        return

    thinking_message = (
        await update.message.reply_text(
            "🤖 در حال بررسی سؤال شما..."
        )
    )

    try:

        input_parts = [
            {
                "type": "input_text",
                "text": user_question,
            }
        ]

        answer, source_urls = (
            await _request_ai(
                input_parts,
                user_question,
                context,
                image_mode=False,
            )
        )

        # =================================================
        # بررسی مجدد عضویت بعد از دریافت پاسخ AI
        # =================================================

        is_member = await ensure_ai_membership(
            update,
            context
        )

        if not is_member:

            try:
                await thinking_message.delete()
            except Exception:
                pass

            return

        await _send_ai_answer(
            update.message,
            answer,
            source_urls,
            edit_message=thinking_message,
        )

    except Exception as e:

        print(
            f"OPENAI TEXT ERROR "
            f"[{type(e).__name__}]: {e}"
        )

        try:

            await thinking_message.edit_text(
                "⚠️ در پردازش سؤال مشکلی ایجاد شد.\n"
                "لطفاً چند لحظه بعد دوباره تلاش کنید."
            )

        except Exception:
            pass


