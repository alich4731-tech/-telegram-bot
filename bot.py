async def _send_ai_answer(
    message,
    answer,
    source_citations=None,
    edit_message=None,
):

    answer = _clean_ai_text(
        answer
    )

    answer = _remove_source_links(
        answer
    )

    source_citations = (
        source_citations
        or []
    )

    answer = _remove_source_links(
        answer
    )

    answer = _clean_ai_text(
        answer
    )

    answer = _remove_source_links(
        answer
    )

    max_text_length = 3500

    chunks = [
        answer[
            i:i + max_text_length
        ]
        for i in range(
            0,
            len(answer),
            max_text_length
        )
    ] or [""]

    if len(chunks) == 1:

        rendered = html.escape(
            chunks[0],
            quote=False
        )

        if edit_message is not None:

            await edit_message.edit_text(
                rendered,
                parse_mode="HTML",
                disable_web_page_preview=True,
            )

        else:

            await message.reply_text(
                rendered,
                parse_mode="HTML",
                disable_web_page_preview=True,
            )

        return

    if edit_message is not None:

        await edit_message.edit_text(
            html.escape(
                chunks[0],
                quote=False
            ),
            parse_mode="HTML",
            disable_web_page_preview=True,
        )

        for chunk in chunks[1:]:

            await message.reply_text(
                html.escape(
                    chunk,
                    quote=False
                ),
                parse_mode="HTML",
                disable_web_page_preview=True,
            )

    else:

        for chunk in chunks:

            await message.reply_text(
                html.escape(
                    chunk,
                    quote=False
                ),
                parse_mode="HTML",
                disable_web_page_preview=True,
            )


