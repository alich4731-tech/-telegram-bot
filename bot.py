# =========================================================

def _normalize_persian(text: str) -> str:

    replacements = {
        "ي": "ی",
        "ى": "ی",
        "ك": "ک",
        "أ": "ا",
        "إ": "ا",
        "آ": "ا",
        "ة": "ه",
        "ؤ": "و",
        "ئ": "ی",
        "ۀ": "ه",
    }

    for old, new in replacements.items():
        text = text.replace(old, new)

    return text


def _normalize_for_match(text: str) -> str:

    text = _normalize_persian(text)
    text = text.replace("\u200c", "")
    text = text.replace(" ", "")

    return text


