# پاک‌سازی citation و نشانه‌های اضافی
# =========================================================

def _remove_empty_citations(text: str) -> str:

    text = re.sub(
        r"\(\s*\)",
        "",
        text
    )

    text = re.sub(
        r"\[\s*\]",
        "",
        text
    )

    text = re.sub(
        r"\[\s*\d+\s*\]",
        "",
        text
    )

    text = re.sub(
        r"\(\s*[\.,;:]*\s*\)",
        "",
        text
    )

    text = re.sub(
        r"\s+([،؛,:.!؟])",
        r"\1",
        text
    )

    text = re.sub(
        r"(?m)^\s*[\(\)\[\]]+\s*$",
        "",
        text
    )

    return text


# =========================================================
# پاک‌سازی نهایی متن AI
# =========================================================

def _clean_ai_text(text: str) -> str:

    if not text:
        return ""

    text = text.replace(
        "```",
        ""
    )

    text = re.sub(
        r"\*\*(.*?)\*\*",
        r"\1",
        text,
        flags=re.S
    )

    text = re.sub(
        r"\*(.*?)\*",
        r"\1",
        text,
        flags=re.S
    )

    text = re.sub(
        r"(?m)^\s*#{1,6}\s*",
        "",
        text
    )

    text = re.sub(
        r"(?m)^\s*[-*]\s+",
        "• ",
        text
    )

    text = re.sub(
        r"\[(.*?)\]\(https?://[^)]+\)",
        r"\1",
        text
    )

    text = re.sub(
        r"https?://\S+",
        "",
        text
    )

    text = _remove_empty_citations(
        text
    )

    text = re.sub(
        r"\n{3,}",
        "\n\n",
        text
    )

    return text.strip()


