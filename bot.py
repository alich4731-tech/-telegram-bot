# =========================================================

async def _request_ai(
    input_parts,
    question_for_history,
    context,
    image_mode=False,
):

    history = context.user_data.setdefault(
        "ai_history",
        []
    )

    recent_history = history[
        -AI_HISTORY_MESSAGES:
    ]

    combined_input = []

    for item in recent_history:

        combined_input.append(
            {
                "role": item["role"],
                "content": item["content"],
            }
        )

    combined_input.append(
        {
            "role": "user",
            "content": input_parts,
        }
    )

    history_text = " ".join(
        item.get(
            "content",
            ""
        )
        for item in recent_history
        if isinstance(
            item.get("content"),
            str
        )
    )

    legal_from_question = (
        _is_legal_question(
            question_for_history
        )
    )

    legal_from_history = (
        _is_legal_question(
            history_text
        )
    )

    legal = (
        legal_from_question
        or legal_from_history
    )

    if legal:

        base_tokens = max(
            AI_MAX_OUTPUT_TOKENS_LEGAL,
            AI_MAX_OUTPUT_TOKENS
        )

    else:

        base_tokens = AI_MAX_OUTPUT_TOKENS

    base_tokens = min(
        base_tokens,
        AI_MAX_OUTPUT_TOKENS_HARD_CAP
    )

    def build_request(
        max_tokens,
        use_search,
        force_search=False,
    ):

        args = {
            "model": AI_MODEL,
            "instructions": AI_SYSTEM_PROMPT,
            "input": combined_input,
            "max_output_tokens": max_tokens,
        }

        if use_search:

            args["tools"] = [
                {
                    "type": "web_search",
                    "search_context_size": AI_WEB_SEARCH_CONTEXT,
                }
            ]

        if force_search:

            args["tool_choice"] = "required"

        return args

    attempts = []

    if legal:

        attempts = [
            {
                "tokens": base_tokens,
                "search": True,
                "required": True,
            },
            {
                "tokens": AI_MAX_OUTPUT_TOKENS_HARD_CAP,
                "search": True,
                "required": True,
            },
        ]

    else:

        attempts = [
            {
                "tokens": base_tokens,
                "search": False,
                "required": False,
            }
        ]

    response = None
    answer = ""

    for index, attempt in enumerate(
        attempts
    ):

        try:

            attempt_response = (
                client.responses.create(
                    **build_request(
                        attempt["tokens"],
                        attempt["search"],
                        attempt["required"],
                    )
                )
            )

        except Exception as call_error:

            print(
                f"OPENAI CALL ERROR "
                f"(attempt {index + 1}) "
                f"[{type(call_error).__name__}]: "
                f"{call_error}"
            )

            continue

        attempt_answer = _extract_output_text(
            attempt_response
        )

        status = getattr(
            attempt_response,
            "status",
            None
        )

        incomplete_details = getattr(
            attempt_response,
            "incomplete_details",
            None
        )

        incomplete_reason = (
            getattr(
                incomplete_details,
                "reason",
                None
            )
            if incomplete_details
            else None
        )

        cut_off = (
            status == "incomplete"
            and incomplete_reason
            == "max_output_tokens"
        )

        if attempt_answer:

            response = (
                attempt_response
            )

            answer = (
                attempt_answer
            )

        if (
            attempt_answer
            and not cut_off
        ):

            break

        print(
            f"AI ATTEMPT {index + 1} "
            f"INSUFFICIENT: "
            f"status={status}, "
            f"incomplete_reason="
            f"{incomplete_reason}, "
            f"empty="
            f"{not attempt_answer}"
        )

    if not answer:

        if legal:

            return (
                "⚠️ برای این سؤال نیاز به بررسی منابع "
                "به‌روز و رسمی وجود دارد، اما در حال حاضر "
                "نتوانستم پاسخ قابل اتکایی از جست‌وجوی منابع "
                "دریافت کنم. لطفاً کمی بعد دوباره تلاش کنید.",
                [],
            )

        return (
            "⚠️ پاسخی از سرویس هوش مصنوعی دریافت نشد. "
            "لطفاً دوباره تلاش کنید.",
            [],
        )

    history.append(
        {
            "role": "user",
            "content": question_for_history[
                :AI_HISTORY_CHAR_LIMIT
            ],
        }
    )

    history.append(
        {
            "role": "assistant",
            "content": answer[
                :AI_HISTORY_CHAR_LIMIT
            ],
        }
    )

    if len(history) > AI_HISTORY_MESSAGES:

        del history[
            :-AI_HISTORY_MESSAGES
        ]

    return (
        answer,
        [],
    )


