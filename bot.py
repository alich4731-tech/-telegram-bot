# لینک‌های دانلود
# =========================================================

async def download_links(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):

    level = context.user_data.get(
        "menu_level"
    )

    if level == "excel_beginner":

        await excel_beginner_download(
            update,
            context
        )

    elif level == "excel_intermediate":

        await excel_intermediate_download(
            update,
            context
        )


