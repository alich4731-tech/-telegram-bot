def _extract_output_text(response) -> str:

    text = (
        getattr(
            response,
            "output_text",
            None
        )
        or ""
    ).strip()

    if text:
        return text

    collected = []

    try:

        for item in (
            getattr(
                response,
                "output",
                []
            )
            or []
        ):

            if getattr(
                item,
                "type",
                None
            ) != "message":
                continue

            for content in (
                getattr(
                    item,
                    "content",
                    []
                )
                or []
            ):

                content_text = getattr(
                    content,
                    "text",
                    None
                )

                if content_text:
                    collected.append(
                        content_text
                    )

    except Exception as e:

        print(
            f"OUTPUT TEXT EXTRACTION WARNING: {e}"
        )

    return "".join(
        collected
    ).strip()


