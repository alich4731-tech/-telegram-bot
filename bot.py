# سوال از هوش مصنوعی
# =========================================================

async def ask_ai(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):
    """ارسال سؤال به OpenAI با تاریخچه محدود و امکان جست‌وجوی وب."""

    if not context.user_data.get("ai_mode", False):
        return

    user_question = update.message.text.strip()

    if not user_question:
        return

    # -----------------------------------------------------
    # محدود کردن ورودی
    # -----------------------------------------------------

    user_question = user_question[:4000]

    # -----------------------------------------------------
    # بررسی اتصال OpenAI
    # -----------------------------------------------------

    if not OPENAI_API_KEY or client is None:

        await update.message.reply_text(
            "⚠️ اتصال هوش مصنوعی تنظیم نشده است.\n"
            "OPENAI_API_KEY را در Environment Variables رندر بررسی کنید."
        )

        return

    # -----------------------------------------------------
    # تاریخچه مکالمه
    # -----------------------------------------------------

    history = context.user_data.setdefault(
        "ai_history",
        []
    )

    recent_history = history[-AI_HISTORY_MESSAGES:]

    input_parts = []

    for item in recent_history:

        input_parts.append({
            "role": item["role"],
            "content": item["content"]
        })

    input_parts.append({
        "role": "user",
        "content": user_question
    })

    # -----------------------------------------------------
    # پیام بررسی
    # -----------------------------------------------------

    thinking_message = await update.message.reply_text(
        "🤖 در حال بررسی سؤال شما..."
    )

    try:

        # -------------------------------------------------
        # تشخیص نیاز به جست‌وجوی وب
        # -------------------------------------------------

        web_search_instruction = """
قبل از پاسخ، بررسی کن آیا سؤال به یکی از موارد زیر مربوط است:

- قانون
- ماده قانونی
- تبصره
- بخشنامه
- آیین‌نامه
- دستورالعمل
- رأی
- نرخ مالیاتی
- نرخ یا مقررات تأمین اجتماعی
- مقررات جاری
- اطلاعاتی که احتمال تغییر آن وجود دارد
- موضوعی که برای پاسخ دقیق به منبع معتبر نیاز دارد

اگر بله، حتماً از Web Search استفاده کن.

برای موضوعات عادی و پایدار که نیاز به منبع به‌روز ندارند،
لازم نیست جست‌وجوی وب انجام دهی.

در موضوعات قانونی، منابع رسمی را در اولویت قرار بده.
"""

        full_instructions = (
            AI_SYSTEM_PROMPT
            + "\n\n"
            + web_search_instruction
        )

        # -------------------------------------------------
        # درخواست به OpenAI
        # -------------------------------------------------

        response = client.responses.create(

            model=AI_MODEL,

            instructions=full_instructions,

            input=input_parts,

            tools=[
                {
                    "type": "web_search",
                    "search_context_size": "medium"
                }
            ],

            max_output_tokens=AI_MAX_OUTPUT_TOKENS
        )

        answer = (response.output_text or "").strip()

        if not answer:

            answer = (
                "⚠️ پاسخی از سرویس هوش مصنوعی دریافت نشد."
            )

        # -------------------------------------------------
        # ذخیره تاریخچه
        # -------------------------------------------------

        history.append({
            "role": "user",
            "content": user_question[:AI_HISTORY_CHAR_LIMIT]
        })

        history.append({
            "role": "assistant",
            "content": answer[:AI_HISTORY_CHAR_LIMIT]
        })

        del history[:-AI_HISTORY_MESSAGES]

        # -------------------------------------------------
        # تقسیم پاسخ‌های طولانی
        # -------------------------------------------------

        max_length = 4000

        if len(answer) <= max_length:

            await thinking_message.edit_text(answer)

        else:

            await thinking_message.edit_text(
                answer[:max_length]
            )

            remaining_text = answer[max_length:]

            while remaining_text:

                chunk = remaining_text[:max_length]

                await update.message.reply_text(
                    chunk
                )

                remaining_text = remaining_text[max_length:]

    except Exception as e:

        print(
            f"OPENAI ERROR [{type(e).__name__}]: {e}"
        )

        await thinking_message.edit_text(
            "⚠️ در پردازش سؤال مشکلی ایجاد شد.\n"
            "لطفاً چند لحظه بعد دوباره تلاش کنید."
        )


