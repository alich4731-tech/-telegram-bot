# بررسی عضویت کانال
# =========================================================

async def check_channel_membership(
    update: Update,
    context: ContextTypes.DEFAULT_TYPE
):
    """
    بررسی می‌کند که کاربر عضو کانال رسمی باشد.

    وضعیت‌های قابل قبول:
    • creator
    • administrator
    • member

    کاربر restricted فقط در صورتی عضو محسوب می‌شود که is_member=True باشد.
    """

    user = update.effective_user

    if not user:
        return False

    try:

        member = await context.bot.get_chat_member(
            chat_id=CHANNEL_USERNAME,
            user_id=user.id,
        )

        status = getattr(
            member,
            "status",
            None
        )

        if status in (
            "creator",
            "administrator",
            "member",
        ):
            return True

        if status == "restricted":
            return bool(
                getattr(
                    member,
                    "is_member",
                    False
                )
            )

        return False

    except Exception as e:

        print(
            f"CHANNEL MEMBERSHIP CHECK ERROR "
            f"[{type(e).__name__}]: {e}"
        )

        return False


