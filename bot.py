def _extract_output_text(response) -> str:

    text = (
        getattr(
            response,
            "output_text",
            None
        )
        or ""
    ).strip()

    if text:
        return text

    collected = []

    try:

        for item in (
            getattr(
                response,
                "output",
                []
            )
            or []
        ):

            if getattr(
                item,
                "type",
                None
            ) != "message":
                continue

            for content in (
                getattr(
                    item,
                    "content",
                    []
                )
                or []
            ):

                content_text = getattr(
                    content,
                    "text",
                    None
                )

                if content_text:
                    collected.append(
                        content_text
                    )

    except Exception as e:

        print(
            f"OUTPUT TEXT EXTRACTION WARNING: {e}"
        )

    return "".join(
        collected
    ).strip()


# =========================================================
# استخراج منابع
# =========================================================

def _collect_source_urls(response):

    citations = []
    seen = set()

    try:

        for item in (
            getattr(
                response,
                "output",
                []
            )
            or []
        ):

            for content in (
                getattr(
                    item,
                    "content",
                    []
                )
                or []
            ):

                for annotation in (
                    getattr(
                        content,
                        "annotations",
                        []
                    )
                    or []
                ):

                    url = getattr(
                        annotation,
                        "url",
                        None
                    )

                    if not url:
                        continue

                    if url in seen:
                        continue

                    seen.add(url)

                    citations.append(
                        {
                            "url": url,
                            "title": getattr(
                                annotation,
                                "title",
                                None
                            ),
                        }
                    )

    except Exception as e:

        print(
            f"SOURCE EXTRACTION WARNING: {e}"
        )

    return citations[:10]


# =========================================================
# پاک‌سازی citation و نشانه‌های اضافی
# =========================================================

def _remove_empty_citations(text: str) -> str:

    text = re.sub(
        r"\(\s*\)",
        "",
        text
    )

    text = re.sub(
        r"\[\s*\]",
        "",
        text
    )

    text = re.sub(
        r"\[\s*\d+\s*\]",
        "",
        text
    )

    text = re.sub(
        r"\(\s*[\.,;:]*\s*\)",
        "",
        text
    )

    text = re.sub(
        r"\s+([،؛,:.!؟])",
        r"\1",
        text
    )

    text = re.sub(
        r"(?m)^\s*[\(\)\[\]]+\s*$",
        "",
        text
    )

    return text


# =========================================================
# پاک‌سازی نهایی متن AI
# =========================================================

def _clean_ai_text(text: str) -> str:

    if not text:
        return ""

    text = text.replace(
        "```",
        ""
    )

    text = re.sub(
        r"\*\*(.*?)\*\*",
        r"\1",
        text,
        flags=re.S
    )

    text = re.sub(
        r"\*(.*?)\*",
        r"\1",
        text,
        flags=re.S
    )

    text = re.sub(
        r"(?m)^\s*#{1,6}\s*",
        "",
        text
    )

    text = re.sub(
        r"(?m)^\s*[-*]\s+",
        "• ",
        text
    )

    text = re.sub(
        r"\[(.*?)\]\(https?://[^)]+\)",
        r"\1",
        text
    )

    text = re.sub(
        r"https?://\S+",
        "",
        text
    )

    text = _remove_empty_citations(
        text
    )

    text = re.sub(
        r"\n{3,}",
        "\n\n",
        text
    )

    return text.strip()


# =========================================================
# حذف لینک‌ها از پاسخ
# =========================================================

def _remove_source_links(text: str) -> str:

    if not text:
        return ""

    text = re.sub(
        r"\[[^\]]*\]\(\s*https?://[^)]*\)",
        "",
        text,
        flags=re.I
    )

    text = re.sub(
        r"<a\b[^>]*href\s*=\s*[\"\']?https?://[^\"\'>\s]+[^>]*>.*?</a>",
        "",
        text,
        flags=re.I | re.S
    )

    text = re.sub(
        r"https?://[^\s<>\]\)]+",
        "",
        text,
        flags=re.I
    )

    text = re.sub(
        r"\bwww\.[a-zA-Z0-9.-]+\.[a-zA-Z]{2,}(?:/[^\s<>\]\)]*)?",
        "",
        text,
        flags=re.I
    )

    text = re.sub(
        r"(?<![\w@])(?:[a-zA-Z0-9-]+\.)+(?:ir|com|net|org|gov|ac|edu|co|info)(?:/[^\s<>\]\)]*)?",
        "",
        text,
        flags=re.I
    )

    text = re.sub(
        r"\(\s*\)",
        "",
        text
    )

    text = re.sub(
        r"\[\s*\]",
        "",
        text
    )

    text = re.sub(
        r"\[\s*\d+(?:\s*[-,]\s*\d+)*\s*\]",
        "",
        text
    )

    text = re.sub(
        r"\s+([،؛,:.!؟])",
        r"\1",
        text
    )

    text = re.sub(
        r"\n{3,}",
        "\n\n",
        text
    )

    return text.strip()


